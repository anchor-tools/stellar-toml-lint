import { describe, expect, it } from 'vitest';
import { parse as parseYaml, parseDocument } from 'yaml';
import {
  CiMatrixWorkflowGenerator,
  DEFAULT_PINNED_ACTIONS,
  DEFAULT_WORKFLOW_PATH,
  SCORECARD_MARKER,
  validateWorkflow,
} from '../src/gitops/ciWorkflowGenerator.js';
import { toYaml, type YamlValue } from '../src/gitops/ciYaml.js';

type Step = Record<string, unknown> & { name?: string; uses?: string; run?: string };
type Job = Record<string, unknown> & { steps: Step[] };

function parsed(generator: CiMatrixWorkflowGenerator): Record<string, unknown> {
  const doc = parseDocument(generator.generate());
  expect(doc.errors).toEqual([]);
  expect(doc.warnings).toEqual([]);
  return doc.toJS() as Record<string, unknown>;
}

function job(workflow: Record<string, unknown>, id: string): Job {
  return (workflow.jobs as Record<string, Job>)[id] as Job;
}

function step(j: Job, name: string): Step {
  const found = j.steps.find((s) => s.name === name);
  expect(found, `step "${name}"`).toBeDefined();
  return found as Step;
}

describe('CiMatrixWorkflowGenerator', () => {
  it('generates syntactically valid YAML that round-trips to the built workflow', () => {
    const generator = new CiMatrixWorkflowGenerator({
      environments: ['development', 'staging', 'testnet', 'public'],
      nodeVersions: ['20', '22', '24'],
    });
    const workflow = parsed(generator);
    expect(workflow).toEqual(JSON.parse(JSON.stringify(generator.build())));
    expect(validateWorkflow(workflow)).toEqual([]);
  });

  it('defaults to testnet and public across Node 20 and 22', () => {
    const generator = new CiMatrixWorkflowGenerator();
    const workflow = parsed(generator);
    const validate = job(workflow, 'validate');
    const matrix = (validate.strategy as { matrix: Record<string, unknown> }).matrix;
    expect(matrix.environment).toEqual(['testnet', 'public']);
    expect(matrix.node).toEqual(['20', '22']);
    expect(matrix.include).toEqual([
      { environment: 'testnet', file: 'environments/testnet/stellar.toml', 'check-network': true },
      { environment: 'public', file: 'environments/public/stellar.toml', 'check-network': true },
    ]);
    expect((validate.strategy as Record<string, unknown>)['fail-fast']).toBe(false);
    expect(generator.workflowPath).toBe(DEFAULT_WORKFLOW_PATH);
    expect(generator.files).toEqual({
      testnet: 'environments/testnet/stellar.toml',
      public: 'environments/public/stellar.toml',
    });
  });

  it('starts with a provenance header that names the regenerate command', () => {
    const yaml = new CiMatrixWorkflowGenerator({
      environments: ['public'],
      nodeVersions: ['22'],
    }).generate();
    expect(yaml.split('\n')[0]).toBe('# Generated by stellar-toml-lint 0.1.0 (init-ci).');
    expect(yaml).toContain('init-ci --matrix public --node 22 --force');
    expect(yaml.endsWith('\n')).toBe(true);
  });

  it('triggers on PRs and pushes that touch the tenant files or the workflow', () => {
    const workflow = parsed(new CiMatrixWorkflowGenerator({ branches: ['main', 'release'] }));
    const on = workflow.on as Record<string, Record<string, unknown>>;
    const paths = [
      'environments/testnet/stellar.toml',
      'environments/public/stellar.toml',
      '.stellartomlrc.json',
      DEFAULT_WORKFLOW_PATH,
    ];
    expect(on.pull_request).toEqual({ paths });
    expect(on.push).toEqual({ branches: ['main', 'release'], paths });
    expect(on.workflow_dispatch).toEqual({});
    expect(on).not.toHaveProperty('pull_request_target');
  });

  describe('security hardening', () => {
    const workflow = parsed(new CiMatrixWorkflowGenerator());
    const validate = job(workflow, 'validate');
    const scorecard = job(workflow, 'scorecard');

    it('denies all token permissions by default and grants per job', () => {
      expect(workflow.permissions).toEqual({});
      expect(validate.permissions).toEqual({
        contents: 'read',
        'security-events': 'write',
        actions: 'read',
      });
      expect(scorecard.permissions).toEqual({ 'pull-requests': 'write' });
    });

    it('pins every action to a full commit SHA with a version comment', () => {
      const yaml = new CiMatrixWorkflowGenerator().generate();
      const uses = [...yaml.matchAll(/uses: (\S+)( # (\S+))?/g)];
      expect(uses.length).toBeGreaterThan(0);
      for (const [, ref, , version] of uses) {
        expect(ref).toMatch(/@[0-9a-f]{40}$/);
        expect(version).toMatch(/^v\d+\.\d+\.\d+$/);
      }
      for (const action of Object.values(DEFAULT_PINNED_ACTIONS)) {
        expect(action.sha).toMatch(/^[0-9a-f]{40}$/);
      }
    });

    it('does not persist checkout credentials', () => {
      expect(step(validate, 'Check out').with).toEqual({ 'persist-credentials': false });
    });

    it('never checks out code in the job that holds a write token', () => {
      expect(scorecard.steps.some((s) => s.uses?.startsWith('actions/checkout@'))).toBe(false);
    });

    it('passes matrix and event values to scripts only through env', () => {
      for (const j of [validate, scorecard]) {
        for (const s of j.steps) {
          if (s.run !== undefined) expect(s.run).not.toContain('${{');
        }
      }
    });

    it('installs the tool with lifecycle scripts disabled', () => {
      const install = step(validate, 'Install stellar-toml-lint');
      expect(install.run).toContain('--ignore-scripts');
      expect(install.env).toEqual({ TOOL: 'stellar-toml-lint@0.1.0' });
    });

    it('skips write-scoped steps for fork pull requests', () => {
      expect(step(validate, 'Upload SARIF to code scanning').if).toContain(
        'github.event.pull_request.head.repo.full_name == github.repository',
      );
      expect(scorecard.if).toContain(
        'github.event.pull_request.head.repo.full_name == github.repository',
      );
    });

    it('bounds job runtime and cancels superseded runs', () => {
      expect(validate['timeout-minutes']).toBe(5);
      expect(scorecard['timeout-minutes']).toBe(5);
      expect(workflow.concurrency).toEqual({
        group: '${{ github.workflow }}-${{ github.event.pull_request.number || github.ref }}',
        'cancel-in-progress': true,
      });
    });
  });

  it('caches the tool install and remote assets keyed on the tenant file', () => {
    const validate = job(parsed(new CiMatrixWorkflowGenerator()), 'validate');
    const cache = step(validate, 'Restore tool and remote asset cache');
    const inputs = cache.with as Record<string, string>;
    expect(inputs.path).toBe('~/.npm/_cacache\n.stellar-toml-lint/cache\n');
    expect(inputs.key).toContain('${{ hashFiles(matrix.file) }}');
    expect(inputs['restore-keys']).toBe(
      'stellar-toml-lint-0.1.0-${{ runner.os }}-node${{ matrix.node }}-\n',
    );
    const lint = step(validate, 'Lint ${{ matrix.environment }} stellar.toml');
    expect(lint.env).toMatchObject({ STELLAR_TOML_LINT_ASSET_CACHE: '.stellar-toml-lint/cache' });
    expect(step(validate, 'Install stellar-toml-lint').run).toContain('--prefer-offline');
  });

  it('records the lint exit code without letting bash -e abort the step', () => {
    const validate = job(parsed(new CiMatrixWorkflowGenerator({ strict: true })), 'validate');
    const lint = step(validate, 'Lint ${{ matrix.environment }} stellar.toml');
    expect(lint.run).toContain('&& code=0 || code=$?');
    expect(lint.run).toContain('echo "exit-code=$code" >> "$GITHUB_OUTPUT"');
    expect(lint.env).toMatchObject({ STRICT: 'true' });
    const report = step(validate, 'Assert network isolation and build reports');
    expect(report.if).toBe('always()');
    expect(report.run).toContain('stellar-toml-lint ci-report');
    const fail = step(validate, 'Fail on findings');
    expect(fail.if).toBe('always()');
    expect(fail.run).toContain('exit 1');
  });

  it('uploads SARIF and scorecards once per environment from the primary Node version', () => {
    const validate = job(
      parsed(new CiMatrixWorkflowGenerator({ nodeVersions: ['22', '20'] })),
      'validate',
    );
    const sarif = step(validate, 'Upload SARIF to code scanning');
    expect(sarif.if).toContain("matrix.node == '22'");
    expect(sarif.with).toEqual({
      sarif_file: 'reports/${{ matrix.environment }}.sarif',
      category: 'stellar-toml-lint/${{ matrix.environment }}',
    });
    const artifact = step(validate, 'Upload scorecard');
    expect(artifact.if).toContain("matrix.node == '22'");
    expect((artifact.with as Record<string, unknown>)['retention-days']).toBe(7);
  });

  it('posts a single upserted PR comment marked for the bot', () => {
    const scorecard = job(parsed(new CiMatrixWorkflowGenerator()), 'scorecard');
    expect(scorecard.needs).toBe('validate');
    const post = step(scorecard, 'Post scorecard comment');
    expect(post.env).toEqual({ MARKER: SCORECARD_MARKER });
    const script = (post.with as { script: string }).script;
    expect(script).toContain('github.rest.issues.updateComment');
    expect(script).toContain('github.rest.issues.createComment');
    expect(script).toContain('github.paginate');
    expect(step(scorecard, 'Render scorecard').run).toContain('ci-scorecard --input scorecards');
  });

  it('drops SARIF, PR comment and cache pieces when disabled', () => {
    const generator = new CiMatrixWorkflowGenerator({
      sarif: false,
      prComment: false,
      cache: false,
    });
    const workflow = parsed(generator);
    expect(validateWorkflow(workflow)).toEqual([]);
    expect(Object.keys(workflow.jobs as object)).toEqual(['validate']);
    const validate = job(workflow, 'validate');
    expect(validate.permissions).toEqual({ contents: 'read' });
    const names = validate.steps.map((s) => s.name);
    expect(names).not.toContain('Upload SARIF to code scanning');
    expect(names).not.toContain('Upload scorecard');
    expect(names).not.toContain('Restore tool and remote asset cache');
    expect(step(validate, 'Lint ${{ matrix.environment }} stellar.toml').env).not.toHaveProperty(
      'STELLAR_TOML_LINT_ASSET_CACHE',
    );
  });

  it('honours file overrides, file patterns and network-check settings', () => {
    const forced = new CiMatrixWorkflowGenerator({
      environments: ['staging', 'public'],
      filePattern: 'tenants/{environment}/.well-known/stellar.toml',
      files: { public: 'public/.well-known/stellar.toml' },
      checkNetwork: false,
    });
    expect(forced.files).toEqual({
      staging: 'tenants/staging/.well-known/stellar.toml',
      public: 'public/.well-known/stellar.toml',
    });
    const include = (job(parsed(forced), 'validate').strategy as { matrix: { include: unknown[] } })
      .matrix.include;
    expect(include).toEqual([
      {
        environment: 'staging',
        file: 'tenants/staging/.well-known/stellar.toml',
        'check-network': false,
      },
      { environment: 'public', file: 'public/.well-known/stellar.toml', 'check-network': false },
    ]);

    const perEnv = new CiMatrixWorkflowGenerator({
      environments: ['development', 'testnet'],
      checkNetwork: { development: true },
    });
    const perEnvInclude = (perEnv.build().jobs as Record<string, Job>).validate as Job;
    expect(
      (
        perEnvInclude.strategy as { matrix: { include: { 'check-network': boolean }[] } }
      ).matrix.include.map((i) => i['check-network']),
    ).toEqual([true, true]);
  });

  it('accepts custom names, timeouts and action pins', () => {
    const generator = new CiMatrixWorkflowGenerator({
      workflowName: 'Anchor tenants',
      timeoutMinutes: 10,
      workflowPath: '.github/workflows/anchors.yml',
      toolVersion: '1.2.3-beta.1',
      actions: {
        checkout: { uses: 'actions/checkout', sha: 'a'.repeat(40), version: 'v9.9.9' },
      },
    });
    const yaml = generator.generate();
    expect(yaml).toContain(`actions/checkout@${'a'.repeat(40)} # v9.9.9`);
    expect(yaml).toContain('stellar-toml-lint@1.2.3-beta.1');
    const workflow = parsed(generator);
    expect(workflow.name).toBe('Anchor tenants');
    expect(job(workflow, 'validate')['timeout-minutes']).toBe(10);
    expect((workflow.on as { push: { paths: string[] } }).push.paths).toContain(
      '.github/workflows/anchors.yml',
    );
  });

  it.each([
    [{ environments: [] }, 'At least one environment'],
    [{ environments: ['testnet', 'testnet'] }, 'unique'],
    [{ environments: ['moon'] }, 'Unknown environment "moon"'],
    [{ nodeVersions: [] }, 'At least one Node.js version'],
    [{ nodeVersions: ['lts/*'] }, 'Invalid Node.js version'],
    [{ nodeVersions: ['18'] }, 'requires Node.js 20'],
    [{ filePattern: '../secrets/{environment}.toml' }, 'Unsafe file'],
    [{ files: { testnet: '/etc/stellar.toml' } }, 'Unsafe file'],
    [{ files: { testnet: 'a$(whoami).toml' } }, 'Unsafe file'],
    [{ files: { testnet: '  ' } }, 'Unsafe file'],
    [{ files: { testnet: 'a\tb.toml' } }, 'Unsafe file'],
    [{ toolVersion: 'latest' }, 'exact semver'],
    [{ timeoutMinutes: 0 }, 'timeoutMinutes'],
    [{ timeoutMinutes: 1.5 }, 'timeoutMinutes'],
    [{ timeoutMinutes: 361 }, 'timeoutMinutes'],
    [{ branches: ['main;rm'] }, 'Unsafe branch'],
    [{ workflowPath: '../x.yml' }, 'Unsafe workflow path'],
    [
      { actions: { cache: { uses: 'actions/cache', sha: 'v4', version: 'v4' } } },
      'full 40-character',
    ],
    [{ workflowName: 'a\nb' }, 'single line'],
  ])('rejects invalid options %#', (options, error) => {
    expect(
      () =>
        new CiMatrixWorkflowGenerator(
          options as ConstructorParameters<typeof CiMatrixWorkflowGenerator>[0],
        ),
    ).toThrow(error);
  });
});

describe('validateWorkflow', () => {
  const valid = () =>
    JSON.parse(JSON.stringify(new CiMatrixWorkflowGenerator().build())) as {
      [key: string]: unknown;
      jobs: Record<string, Job>;
    };

  it('accepts the generated workflow', () => {
    expect(validateWorkflow(valid())).toEqual([]);
  });

  it('rejects non-mappings', () => {
    expect(validateWorkflow('name: x')).toEqual(['workflow must be a mapping']);
    expect(validateWorkflow(null)).toEqual(['workflow must be a mapping']);
  });

  it('reports top-level schema problems', () => {
    const problems = validateWorkflow({ nmae: 'x', on: {}, jobs: {} });
    expect(problems).toEqual([
      'unknown top-level key "nmae"',
      'workflow needs a name',
      '"on" must map at least one event',
      'top-level permissions must be set explicitly',
      '"jobs" must define at least one job',
    ]);
  });

  it('flags pull_request_target, unknown events and broad permissions', () => {
    const w = valid();
    w.on = { pull_request_target: {}, issue_comment: {} };
    w.permissions = 'write-all';
    expect(validateWorkflow(w)).toEqual([
      'pull_request_target runs fork code with a write token; use pull_request',
      'unsupported event "issue_comment"',
      'workflow: broad "write-all" permissions; grant individual scopes instead',
    ]);
    w.permissions = ['contents'];
    w.on = { push: {} };
    expect(validateWorkflow(w)).toEqual(['workflow: permissions must be a mapping']);
    w.permissions = { contents: 'admin', secrets: 'read' };
    expect(validateWorkflow(w)).toEqual([
      'workflow: permission "contents" must be read, write, or none',
      'workflow: unknown permission "secrets"',
    ]);
  });

  it('reports job-level schema and hardening problems', () => {
    const w = valid();
    const validate = w.jobs.validate as Job;
    delete validate['runs-on'];
    delete validate.permissions;
    validate['timeout-minutes'] = 0;
    validate.needs = ['ghost'];
    validate.services2 = {};
    validate.strategy = { matrix: { environment: [] } };
    validate.steps[0] = { uses: 'actions/checkout@v4', with: { 'persist-credentials': true } };
    expect(validateWorkflow(w)).toEqual([
      'jobs.validate: unknown key "services2"',
      'jobs.validate: missing runs-on',
      'jobs.validate: permissions must be set explicitly',
      'jobs.validate: timeout-minutes must be a positive number',
      'jobs.validate: needs unknown job "ghost"',
      'jobs.validate: matrix axis "environment" must be a non-empty list',
      'jobs.validate.steps[0]: "actions/checkout@v4" is not pinned to a full commit SHA',
      'jobs.validate: actions/checkout must set persist-credentials: false',
    ]);
  });

  it('reports malformed jobs and steps', () => {
    const w = valid();
    w.jobs = {
      '1bad': { 'runs-on': 'x', permissions: {}, 'timeout-minutes': 1, steps: [] },
      notmap: 'x' as unknown as Job,
      nomatrix: {
        'runs-on': 'x',
        permissions: {},
        'timeout-minutes': 1,
        strategy: 'x',
        steps: [
          'x',
          { run: 'echo ${{ github.event.pull_request.title }}', bogus: 1 },
          { uses: `a/b@${'0'.repeat(40)}`, run: 'x' },
          {},
          { run: 'x', with: { a: 1 } },
          { uses: `a/b@${'0'.repeat(40)}`, with: 'x' },
          { uses: `a/b@${'0'.repeat(40)}`, with: { list: [1], map: { a: 1 } } },
          { id: 'dup', run: 'x' },
          { id: 'dup', run: 'echo ${{ github.head_ref }}' },
        ],
      } as unknown as Job,
    };
    expect(validateWorkflow(w)).toEqual([
      'jobs.1bad: invalid job id',
      'jobs.1bad: steps must be a non-empty list',
      'jobs.notmap: must be a mapping',
      'jobs.nomatrix: strategy.matrix must be a mapping',
      'jobs.nomatrix.steps[0]: must be a mapping',
      'jobs.nomatrix.steps[1]: unknown key "bogus"',
      'jobs.nomatrix.steps[1]: run interpolates untrusted event data; pass it through env',
      'jobs.nomatrix.steps[2]: needs exactly one of uses or run',
      'jobs.nomatrix.steps[3]: needs exactly one of uses or run',
      'jobs.nomatrix.steps[4]: "with" requires "uses"',
      'jobs.nomatrix.steps[5]: "with" must be a mapping',
      'jobs.nomatrix.steps[6]: input "list" must be a scalar',
      'jobs.nomatrix.steps[6]: input "map" must be a scalar',
      'jobs.nomatrix.steps[8]: run interpolates untrusted event data; pass it through env',
      'jobs.nomatrix.steps[8]: duplicate step id "dup"',
    ]);
  });

  it('accepts a single needs string that names a job', () => {
    const w = valid();
    expect(w.jobs.scorecard?.needs).toBe('validate');
    expect(validateWorkflow(w)).toEqual([]);
    (w.jobs.scorecard as Job).needs = 42;
    expect(validateWorkflow(w)).toEqual(['jobs.scorecard: needs unknown job "42"']);
  });
});

describe('toYaml', () => {
  const roundTrip = (value: YamlValue) => expect(parseYaml(toYaml(value))).toEqual(value);

  it('quotes strings YAML would otherwise reinterpret', () => {
    const tricky = [
      '',
      ' padded',
      'trailing ',
      'true',
      'No',
      'on',
      'null',
      '20',
      '-1',
      '.5',
      '0x1F',
      '- item',
      '#comment',
      'a: b',
      'a #b',
      '*alias',
      '&anchor',
      '!tag',
      '|',
      '>',
      "'single'",
      '"double"',
      '%directive',
      '@at',
      '`tick',
      '{flow}',
      '[flow]',
      'tab\there',
      '<!-- marker -->',
      '${{ matrix.node }}',
      'plain text',
    ];
    roundTrip({ values: tricky });
    roundTrip(Object.fromEntries(tricky.filter((t) => t !== '').map((t, i) => [t, i])));
  });

  it('emits scalars, empty collections and nested sequences', () => {
    const value = {
      on: { workflow_dispatch: {} },
      n: 3,
      f: false,
      t: true,
      z: null,
      empty: [],
      nested: [[1, 2], [], {}, [{ a: 1 }]],
      skipped: undefined,
      multi: ['line one\nline two'],
    };
    const yaml = toYaml(value);
    expect(yaml).toContain('on:\n  workflow_dispatch: {}');
    expect(yaml).not.toContain('skipped');
    expect(parseYaml(yaml)).toEqual({ ...value, skipped: undefined });
    expect(toYaml('scalar')).toBe('scalar\n');
    expect(toYaml(['x'])).toBe('- x\n');
  });

  it('writes multi-line mapping values as literal blocks', () => {
    expect(toYaml({ run: 'echo a\n\necho b\n\n' })).toBe('run: |\n  echo a\n\n  echo b\n');
    roundTrip({ run: 'echo a\n\necho b\n' });
    roundTrip({ run: '  indented first\nnext\n' });
  });

  it('refuses non-finite numbers', () => {
    expect(() => toYaml({ n: Number.NaN })).toThrow('non-finite');
  });
});
